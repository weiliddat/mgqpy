"""Array operators reuse paths and equality; elemMatch binds one element."""

import re

import pytest

from .helpers import assert_matches


@pytest.mark.parametrize("query,documents,hits", [
    ({"x": {"$all": [1, 2]}}, [{"x": [1, 2]}, {"x": [[1, 2]]},
                               {"x": [0, 1, 2]}, {"x": [1]}, {}, {"x": None}], [0, 2]),
    ({"x": {"$all": [1, 2]}}, [{"x": [0] * 160 + [1, 2]},
                               {"x": [0] * 160 + [True, 2]},
                               {"x": [1] + [0] * 160 + [2]},
                               {"x": [0] * 160 + [2]},
                               {"x": [2, 1] + [0] * 160}], [0, 2, 4]),
    ({"x": {"$all": [1]}}, [{"x": 1}, {"x": True}, {"x": [True]},
                            {"x": [1]}, {"x": [[1]]}, {}], [0, 3]),
    ({"x": {"$all": [None]}}, [{}, {"x": None}, {"x": [None]}, {"x": []}], [0, 1, 2]),
    ({"x": {"$all": []}}, [{}, {"x": []}, {"x": [1]}, {"x": None}], []),
    ({"x": {"$all": [[1, 2]]}}, [{"x": [1, 2]}, {"x": [[1, 2]]},
                                {"x": [[[1, 2]]]}, {"x": [2, 1]}], [0, 1]),
    ({"x.y": {"$all": [1, 2]}}, [{"x": [{"y": [1]}, {"y": [2]}]},
                                 {"x": [{"y": 1}, {"y": 2}]},
                                 {"x": [{"y": [[1, 2]]}]}, {"x": []},
                                 {"x": [{"y": [2]}, {"y": [1]}]}], [0, 1, 4]),
    ({"x.0": {"$all": [1]}}, [{"x": [[1]]}, {"x": [1]},
                              {"x": [{"0": 1}]}], [1, 2]),
    ({"x.0": {"$all": [[1]]}}, [{"x": [[1]]}, {"x": [[[1]]]},
                                {"x": [1]}], [0]),
    ({"x.1.y": {"$all": [1, 2]}}, [{"x": [{"y": [1, 2]}]},
                                   {"x": [0, {"y": [1, 2]}]}], [1]),
    ({"x": {"$all": [{"a": 1, "b": 2}]}}, [{"x": [{"a": 1, "b": 2}]},
                                            {"x": [{"b": 2, "a": 1}]}], [0]),
    # First-key classification must not mistake a later $ key for an expression.
    ({"x": {"$all": [{"a": 1, "$eq": 2}]}}, [{"x": [{"a": 1, "$eq": 2}]},
                                              {"x": [{"a": 1, "$eq": 3}]}], [0]),
    ({"x": {"$all": [{"a": 1, "$elemMatch": 2}]}},
     [{"x": [{"a": 1, "$elemMatch": 2}]}, {"x": [{"a": 1, "$elemMatch": 3}]}], [0]),
    ({"x": {"$all": [float("nan")]}}, [{"x": [float("nan")]}, {"x": [0]}], [0]),
    ({"x": {"$all": [re.compile("^a"), re.compile("z$")]}},
     [{"x": ["abc", "xyz"]}, {"x": "az"}, {"x": ["abc"]}, {"x": [["az"]]}], [0, 1]),
    ({"x": {"$all": [{"$elemMatch": {"n": {"$gt": 50}, "s": "M"}},
                      {"$elemMatch": {"n": 100, "c": "green"}}]}}, [
        {"x": [{"n": 60, "s": "M"}, {"n": 100, "c": "green"}]},
        {"x": [{"n": 100, "s": "M", "c": "green"}]},
        {"x": [{"n": 60}, {"s": "M"}, {"n": 100, "c": "green"}]},
    ], [0, 1]),
    ({"x": {"$elemMatch": {"a": {"$gt": 10}, "b": {"$lt": 100}}}}, [
        {"x": [{"a": 20, "b": 90}]}, {"x": [{"a": 20}, {"b": 90}]},
        {"x": [{"a": 20, "b": 100}, {"a": 10, "b": 90}]}, {"x": None},
    ], [0]),
    ({"x.y": {"$elemMatch": {"a": 1, "b": 2}}}, [
        {"x": [{"y": [{"a": 1, "b": 2}]}]},
        {"x": {"y": [{"a": 1}, {"b": 2}]}}, {"x": {}},
    ], [0]),
    ({"x.0.y": {"$elemMatch": {"a": 1}}}, [
        {"x": [{"y": [{"a": 1}]}]}, {"x": [0, {"y": [{"a": 1}]}]},
    ], [0]),
    ({"x": {"$elemMatch": {"a": {"$exists": False}}}}, [
        {"x": [1, None]}, {"x": [{"a": 1}]}, {"x": [[{"a": 1}]]}, {"x": [{}]},
    ], [2, 3]),
    ({"x": {"$size": 2}}, [{"x": [1, "a"]}, {"x": [{}, {}]},
                            {"x": [1]}, {"x": None}, {}], [0, 1]),
    ({"x": {"$size": 0}}, [{"x": []}, {}, {"x": None}, {"x": [[]]}], [0]),
    ({"x.y": {"$size": 2.0}}, [{"x": [{"y": [1]}, {"y": [2, 3]}]},
                               {"x": [{"y": [1]}, {"y": [2]}]}], [0]),
    ({"x.0.y": {"$size": 2}}, [{"x": [{"y": [1, 2]}]},
                               {"x": [{"y": [1]}, {"y": [2, 3]}]}], [0]),
    ({"x": {"$size": 2147483647}}, [{"x": []}, {"x": [1, 2]}], []),
    ({"x": {"$size": 2147483647.0}}, [{"x": []}, {"x": [1, 2]}], []),
])
def test_array_operators(test_db, query, documents, hits):
    assert_matches(test_db, query, documents, hits)
